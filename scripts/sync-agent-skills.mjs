import {
  mkdir,
  readFile,
  readdir,
  realpath,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

export const referenceSkills = ["uni-app", "web-design-guidelines"];
const marker = "<!-- Generated by scripts/sync-agent-skills.mjs -->";

export async function planSkillEntries(root) {
  const projectSkills = await readdir(path.join(root, ".agent/skills"), {
    withFileTypes: true,
  });
  const entries = [];

  async function addEntry(source, destination) {
    const sourceText = await readFile(path.join(root, source), "utf8");
    const metadata = /^---\r?\n[\s\S]*?\r?\n---(?=\r?\n|$)/u.exec(sourceText);
    if (!metadata) throw new Error(`Missing Skill frontmatter in ${source}`);
    const link = path.posix.relative(path.posix.dirname(destination), source);
    entries.push({
      relativePath: destination,
      content: `${metadata[0].replaceAll("\r\n", "\n")}\n\n${marker}\n\nRead and follow the [project Skill](${link}). Resolve its supporting files relative to that Skill.\n`,
    });
  }

  for (const { name } of projectSkills.filter((entry) => entry.isDirectory())) {
    if (referenceSkills.includes(name)) {
      throw new Error(
        `Project Skill conflicts with bundled reference: ${name}`,
      );
    }
    for (const client of [".agents", ".claude"]) {
      await addEntry(
        `.agent/skills/${name}/SKILL.md`,
        `${client}/skills/${name}/SKILL.md`,
      );
    }
  }
  for (const name of referenceSkills) {
    await addEntry(
      `.agents/skills/${name}/SKILL.md`,
      `.claude/skills/${name}/SKILL.md`,
    );
  }
  return entries.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
}

async function readOptional(file) {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return undefined;
    throw error;
  }
}

async function sync(root, check) {
  const entries = await planSkillEntries(root);
  const pending = [];
  for (const entry of entries) {
    const file = path.join(root, entry.relativePath);
    const existing = await readOptional(file);
    if (existing?.replaceAll("\r\n", "\n") === entry.content) continue;
    if (existing !== undefined && !existing.includes(marker)) {
      throw new Error(`A custom Skill already owns ${entry.relativePath}`);
    }
    pending.push({ file, ...entry, create: existing === undefined });
  }

  // A removed or renamed Skill can still appear in a client's menu. Surface
  // its old entry for the author without removing any local files.
  const expected = new Set(entries.map((entry) => entry.relativePath));
  for (const client of [".agents", ".claude"]) {
    const dir = `${client}/skills`;
    let folders;
    try {
      folders = await readdir(path.join(root, dir), { withFileTypes: true });
    } catch (error) {
      if (error.code === "ENOENT") continue;
      throw error;
    }
    for (const folder of folders.filter((entry) => entry.isDirectory())) {
      const file = `${dir}/${folder.name}/SKILL.md`;
      if (expected.has(file)) continue;
      const content = await readOptional(path.join(root, file));
      if (content?.includes(marker))
        throw new Error(`Remove obsolete entry ${file}`);
    }
  }
  if (check && pending.length) {
    throw new Error(
      `Skill entries need sync:\n${pending.map((entry) => entry.relativePath).join("\n")}`,
    );
  }
  for (const entry of pending) {
    await mkdir(path.dirname(entry.file), { recursive: true });
    await writeFile(entry.file, entry.content, {
      flag: entry.create ? "wx" : "w",
    });
  }
  console.log(`Verified ${entries.length} native Skill entries.`);
}

if (
  process.argv[1] &&
  (await realpath(process.argv[1])) === fileURLToPath(import.meta.url)
) {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  await sync(path.resolve(import.meta.dirname, ".."), values.check);
}
